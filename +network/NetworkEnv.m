classdef NetworkEnv
    %NETWORKENV  Fixed wireless sensor network: deployment, routing, traffic, radio.
    %
    %   Holds everything about the network that does NOT depend on the MAC
    %   protocol settings, so every S-MAC configuration is tested on exactly
    %   the same nodes, routes and packets (common random numbers):
    %
    %     Deployment  N nodes placed uniformly at random in the field, with
    %                 the sink at the centre. Re-drawn until every node can
    %                 reach the sink.
    %     Routing     Minimum-energy multi-hop routes (link cost = d^2, links
    %                 only within CommRadius), found with Dijkstra. Each node
    %                 stores only its next hop, as in a real routing table.
    %     Traffic     Every node generates packets as a Poisson process with
    %                 mean interval PacketInterval. Generation stops DrainTime
    %                 seconds before the end so late packets can still arrive.
    %     Radio       Power draw per radio state (Mica2 / CC1000-class values,
    %                 as used in the S-MAC paper) and packet air times.
    %
    %   Typical use:
    %       env = network.NetworkEnv('NumNodes', 20);
    %       env.NextHop        % N x 1, next hop of every node (N+1 = sink)
    %       env.HopCount       % N x 1, hops from every node to the sink
    %
    %   Requires MATLAB R2021a or newer.

    properties (SetAccess = immutable)
        % --- Geometry ---
        NumNodes            % number of sensor nodes N (the sink is vertex N+1)
        AreaSize            % [width height] of the field (m)
        SinkPosition        % [x y] of the sink (m)
        CommRadius          % radio range: nodes closer than this can hear each other (m)
        Positions           % N x 2 node coordinates (m)

        % --- Topology ---
        Neighbors           % (N+1) x (N+1) logical, true if two vertices hear each other
        NextHop             % N x 1 next hop towards the sink
        HopCount            % N x 1 hops to the sink
        Routes              % N x 1 cell, full vertex path from each node to the sink

        % --- Traffic ---
        PacketInterval      % mean time between packets generated by one node (s)
        SimulationTime      % simulated time per evaluation (s)
        DrainTime           % no new packets in the last DrainTime seconds (s)
        ArrivalTimes        % P x 1 packet generation times, sorted (s)
        ArrivalNodes        % P x 1 node that generated each packet

        % --- Radio (power in W, sizes in bytes, rate in bit/s) ---
        DataRate
        PowerTx
        PowerRx
        PowerIdle
        PowerSleep
        BatteryEnergy       % usable energy of one node's battery (J)
        DataBytes
        ControlBytes        % RTS, CTS and ACK
        SyncBytes
    end

    methods
        function obj = NetworkEnv(options)
            arguments
                options.NumNodes (1,1) double {mustBeInteger, mustBePositive} = 20
                options.AreaSize (1,2) double {mustBePositive} = [100 100]
                options.CommRadius (1,1) double {mustBePositive} = 30
                options.PacketInterval (1,1) double {mustBePositive} = 40
                options.SimulationTime (1,1) double {mustBePositive} = 400
                options.DrainTime (1,1) double {mustBeNonnegative} = 30
                options.DeploymentSeed (1,1) double = 1
                options.TrafficSeed (1,1) double = 2
                options.DataRate (1,1) double {mustBePositive} = 20e3
                options.PowerTx (1,1) double {mustBePositive} = 24.75e-3
                options.PowerRx (1,1) double {mustBePositive} = 13.5e-3
                options.PowerIdle (1,1) double {mustBePositive} = 13.5e-3
                options.PowerSleep (1,1) double {mustBePositive} = 15e-6
                options.BatteryEnergy (1,1) double {mustBePositive} = 1e4
                options.DataBytes (1,1) double {mustBePositive} = 100
                options.ControlBytes (1,1) double {mustBePositive} = 10
                options.SyncBytes (1,1) double {mustBePositive} = 9
            end
            assert(options.DrainTime < options.SimulationTime, 'NetworkEnv:badTimes', ...
                'DrainTime must be shorter than SimulationTime.');

            obj.NumNodes = options.NumNodes;
            obj.AreaSize = options.AreaSize;
            obj.SinkPosition = options.AreaSize / 2;
            obj.CommRadius = options.CommRadius;
            obj.PacketInterval = options.PacketInterval;
            obj.SimulationTime = options.SimulationTime;
            obj.DrainTime = options.DrainTime;

            obj.DataRate = options.DataRate;
            obj.PowerTx = options.PowerTx;
            obj.PowerRx = options.PowerRx;
            obj.PowerIdle = options.PowerIdle;
            obj.PowerSleep = options.PowerSleep;
            obj.BatteryEnergy = options.BatteryEnergy;
            obj.DataBytes = options.DataBytes;
            obj.ControlBytes = options.ControlBytes;
            obj.SyncBytes = options.SyncBytes;

            % --- Deployment + routing (own stream: independent of the global rng) ---
            deploy_stream = RandStream('mt19937ar', 'Seed', options.DeploymentSeed);
            [obj.Positions, obj.Neighbors, obj.Routes] = network.NetworkEnv.deployConnected( ...
                deploy_stream, options.NumNodes, options.AreaSize, obj.SinkPosition, options.CommRadius);
            obj.NextHop = cellfun(@(r) r(2), obj.Routes);
            obj.HopCount = cellfun(@numel, obj.Routes) - 1;

            % --- Poisson traffic, identical for every MAC configuration ---
            traffic_stream = RandStream('mt19937ar', 'Seed', options.TrafficSeed);
            [obj.ArrivalTimes, obj.ArrivalNodes] = network.NetworkEnv.poissonTraffic(traffic_stream, ...
                options.NumNodes, options.PacketInterval, options.SimulationTime - options.DrainTime);
        end

        function t = airTime(obj, num_bytes)
            %AIRTIME  Seconds needed to transmit num_bytes at DataRate.
            t = 8 * num_bytes / obj.DataRate;
        end

        function n = numPackets(obj)
            n = numel(obj.ArrivalTimes);
        end
    end

    methods (Static, Access = private)
        function [positions, neighbors, routes] = deployConnected(stream, num_nodes, area, sink, radius)
            %DEPLOYCONNECTED  Random deployment, redrawn until every node reaches the sink.
            max_attempts = 1000;
            for attempt = 1:max_attempts
                positions = rand(stream, num_nodes, 2) .* area;
                points = [positions; sink];
                dist = sqrt((points(:,1) - points(:,1)').^2 + (points(:,2) - points(:,2)').^2);
                neighbors = dist <= radius & ~eye(num_nodes + 1);

                % Minimum-energy routing: link cost d^2 (radio TX energy grows with d^2).
                graph_net = graph((dist.^2 + eps) .* neighbors);
                routes = cell(num_nodes, 1);
                for i = 1:num_nodes
                    routes{i} = shortestpath(graph_net, i, num_nodes + 1);
                end
                if all(~cellfun(@isempty, routes))
                    return;
                end
            end
            error('NetworkEnv:notConnected', ...
                'No connected deployment found in %d attempts; increase CommRadius or NumNodes.', max_attempts);
        end

        function [times, nodes] = poissonTraffic(stream, num_nodes, mean_interval, end_time)
            %POISSONTRAFFIC  Merged Poisson arrivals of all nodes, sorted by time.
            % Draw enough exponential gaps for every node, keep those before end_time.
            expected = end_time / mean_interval;
            num_draws = ceil(expected + 6 * sqrt(expected) + 10);   % > 6 sigma head-room
            gaps = -mean_interval * log(rand(stream, num_draws, num_nodes));
            arrival = cumsum(gaps, 1);
            node_id = repmat(1:num_nodes, num_draws, 1);
            keep = arrival < end_time;
            [times, order] = sort(arrival(keep));
            node_id = node_id(keep);
            nodes = node_id(order);
        end
    end
end
